export function unitAr(u) {
  if (UNIT_AR[u]) return UNIT_AR[u]
  let m = u.match(/^(\d+) to (\d+) bedrooms?( homes)?$/)
  if (m) return `من ${m[1]} إلى ${m[2]} غرف نوم`
  m = u.match(/^(\d+) bedrooms?$/)
  if (m) return `${m[1]} غرف نوم`
  if (u.startsWith('Residential (84 feddans')) return 'سكني على مساحة 84 فدانًا باستثمارات 13.5 مليار جنيه'
  return u
}
export function deliveryAr(d) {
  if (!d) return null
  return d
    .replace(/(\d{4}) to (\d{4})/, '$1 إلى $2')
    .replace('(by phase)', '(حسب المرحلة)')
    .replace('(Palm Hills phases)', '(مراحل بالم هيلز)')
}
